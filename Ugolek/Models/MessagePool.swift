    /// Случайный выбор без повтора последней использованной фразы
    static func random(excluding last: String? = nil) -> String {
        guard phrases.count > 1 else { return phrases.first ?? "" }
        let pool = last.flatMap { lastPhrase in
            phrases.filter { $0 != lastPhrase }
        } ?? phrases
        return pool.randomElement() ?? phrases[0]
    }
